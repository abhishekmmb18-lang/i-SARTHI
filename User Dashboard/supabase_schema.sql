ALTER TABLE road_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE drowsiness_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE sensor_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE drowsiness_bundles ENABLE ROW LEVEL SECURITY;
ALTER TABLE pothole_clusters ENABLE ROW LEVEL SECURITY;

