-- 3. Road Events Table (Potholes, Critical Vibration, SOS, Alcohol Alerts, etc.)
CREATE TABLE IF NOT EXISTS road_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT DEFAULT 'Unknown',
    confidence REAL DEFAULT 0,
    vibration REAL DEFAULT 0,
    latitude DOUBLE PRECISION DEFAULT 0.0,
    longitude DOUBLE PRECISION DEFAULT 0.0,
    distance REAL DEFAULT -1,
    temperature REAL DEFAULT 0,
    humidity REAL DEFAULT 0,
    alcohol REAL DEFAULT 0,
    network_strength BOOLEAN DEFAULT FALSE,
    sos_alert BOOLEAN DEFAULT FALSE,
    gsm_connected BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Index for road event queries
CREATE INDEX IF NOT EXISTS idx_road_events_created_at ON road_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_road_events_type ON road_events(type);

-- 4. Drowsiness Logs Table (Driver Monitoring System)
CREATE TABLE IF NOT EXISTS drowsiness_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_drowsy BOOLEAN DEFAULT FALSE,
    events_count INTEGER DEFAULT 0,
    timestamp TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_drowsiness_logs_timestamp ON drowsiness_logs(timestamp DESC);

-- 5. Sensor Logs Table (Raw Sensor Telemetry: GPS, Alcohol, Radar, Vibration)
CREATE TABLE IF NOT EXISTS sensor_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_type TEXT NOT NULL, -- 'GPS', 'Alcohol', 'Radar', 'Vibration'
    value_1 DOUBLE PRECISION DEFAULT 0, -- Lat, Alcohol %, or Left Vib, or Angle
    value_2 DOUBLE PRECISION DEFAULT 0, -- Lon, Right Vib, or Distance
    value_3 DOUBLE PRECISION DEFAULT 0, -- Speed, etc.
    timestamp TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_sensor_logs_sensor_type ON sensor_logs(sensor_type);
CREATE INDEX IF NOT EXISTS idx_sensor_logs_timestamp ON sensor_logs(timestamp DESC);

-- 6. Drowsiness Incident Bundles (Clusters of 5x Drowsiness in 2 mins)
CREATE TABLE IF NOT EXISTS drowsiness_bundles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT DEFAULT 'CRITICAL_FATIGUE_CLUSTER_5X',
    events_count INTEGER DEFAULT 5,
    payload_json JSONB,
    external_server_status TEXT DEFAULT 'PENDING',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_drowsiness_bundles_created_at ON drowsiness_bundles(created_at DESC);

-- 7. 10-Vehicle / 10-Pass Spatial Pothole Clusters & OpenAI Work Orders
CREATE TABLE IF NOT EXISTS pothole_clusters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id TEXT UNIQUE NOT NULL,
    center_lat DOUBLE PRECISION DEFAULT 0.0,
    center_lng DOUBLE PRECISION DEFAULT 0.0,
    verified_count INTEGER DEFAULT 1,
    status TEXT DEFAULT 'PENDING', -- 'PENDING', 'VERIFIED_10X', 'DISPATCHED'
    max_vibration REAL DEFAULT 0,
    avg_speed REAL DEFAULT 0,
    raw_logs_json JSONB,
    ai_severity_score REAL DEFAULT 0,
    ai_report TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_pothole_clusters_created_at ON pothole_clusters(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_pothole_clusters_status ON pothole_clusters(status);

